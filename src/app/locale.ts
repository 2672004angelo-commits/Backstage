const originalText = new WeakMap<Text, { source: string; last: string }>();
const originalAttributes = new WeakMap<Element, Map<string, { source: string; last: string }>>();

function translated(value: string, language: Language) {
  const trimmed = value.trim();
  const replacement = language === "en"
    ? translations[trimmed] || trimmed
    : trimmed;
  return value.replace(trimmed, replacement);
}

function translateTextNode(node: Text, language: Language) {
  const value = node.nodeValue || "";
  const previous = originalText.get(node);
  const source = previous && value === previous.last ? previous.source : value;
  const replacement = translated(source, language);
  if (replacement !== value) node.nodeValue = replacement;
  originalText.set(node, { source, last: replacement });
}

function translateAttribute(element: Element, name: string, language: Language) {
  const value = element.getAttribute(name);
  if (!value) return;
  let attributes = originalAttributes.get(element);
  if (!attributes) {
    attributes = new Map();
    originalAttributes.set(element, attributes);
  }
  const previous = attributes.get(name);
  const source = previous && value === previous.last ? previous.source : value;
  const replacement = translated(source, language);
  if (replacement !== value) element.setAttribute(name, replacement);
  attributes.set(name, { source, last: replacement });
}

function translateNode(node: Node, language: Language) {
  if (node.nodeType === Node.TEXT_NODE) {
    translateTextNode(node as Text, language);
    return;
  }
  const textNodes = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
  while (textNodes.nextNode()) {
    translateTextNode(textNodes.currentNode as Text, language);
  }

  if (node instanceof Element) {
    const attributeNames = ["alt", "aria-label", "placeholder", "title"];
    for (const element of [node, ...node.querySelectorAll("*")]) {
      for (const name of attributeNames) translateAttribute(element, name, language);
    }
  }
}

export function applyLanguage(language: Language) {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  window.localStorage.setItem("backstage-language", language);
  translateNode(document.body, language);
}

export function observeLanguage(language: Language, onChange: (language: Language) => void) {
  let currentLanguage = language;
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData" && record.target.nodeType === Node.TEXT_NODE) {
        translateTextNode(record.target as Text, currentLanguage);
      }
      for (const node of record.addedNodes) translateNode(node, currentLanguage);
      if (record.type === "attributes" && record.target instanceof Element) {
        const name = record.attributeName;
        if (name) translateAttribute(record.target, name, currentLanguage);
      }
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["alt", "aria-label", "placeholder", "title"],
  });
  const changeLanguage = (event: Event) => {
    const nextLanguage = (event as CustomEvent<Language>).detail;
    if (nextLanguage !== "ar" && nextLanguage !== "en") return;
    currentLanguage = nextLanguage;
    onChange(nextLanguage);
    applyLanguage(nextLanguage);
  };
  window.addEventListener("backstage-language-change", changeLanguage);
  return () => {
    observer.disconnect();
    window.removeEventListener("backstage-language-change", changeLanguage);
  };
}
